#!/usr/bin/env python3
"""Generates app/orch_cc_tables.inc: the MIDI value laws of orch_cc.c.

Every table has 128 entries, one per MIDI value, so every step of a velocity
or a controller does something, and the steps are even where the ear hears
evenly: in decibels for levels, on a log scale for times and rates.

VEL_OUT_Q12 is the output share of a note's velocity. The models already get
louder with velocity on their own (harder bow, more breath), by about 20 dB
from 1 to 127: tests/velocity_model.txt, the mean over all 18 instruments at
C3 and G4. This table adds what is missing to put the whole
note on an even line: 1 -> -VEL_RANGE_DB, 127 -> 0 dB, equal dB per step.
"""
import math, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
VEL_RANGE_DB = 32.0

def model_curves():
    """one curve per family, relative to its own velocity 127"""
    cols = None
    for line in (ROOT / "tests" / "velocity_model.txt").read_text().split("\n"):
        if not line.strip() or line.startswith("#"):
            continue
        f = line.split()
        if cols is None:
            cols = [dict() for _ in f[1:]]
        for k, db in enumerate(f[1:]):
            cols[k][int(f[0])] = float(db)
    curves = []
    for mp in cols:
        sm = {}
        for v in sorted(mp):
            w = [mp[u] for u in mp if abs(u - v) <= 4]
            sm[v] = sum(w) / len(w)
        for v in range(2, 128):
            sm[v] = max(sm[v], sm[v - 1])
        curves.append({v: sm[v] - sm[127] for v in sm})
    return curves

def table(name, ctype, values, per_line=8):
    out = [f"static const {ctype} {name}[128] = {{"]
    for i in range(0, 128, per_line):
        out.append("    " + ", ".join(f"{x}U" for x in values[i:i + per_line]) + ",")
    out.append("};")
    return "\n".join(out)

def log_law(lo, hi, zero=None):
    vals = []
    for c in range(128):
        if c == 0 and zero is not None:
            vals.append(zero)
            continue
        x = c / 127.0
        vals.append(int(round(lo * (hi / lo) ** x)))
    return vals

def main():
    vel_rows = []
    for model in model_curves():
        row = [0]
        for v in range(1, 128):
            want = -VEL_RANGE_DB * (127 - v) / 126.0
            row.append(min(65535, int(round(4064 * 10 ** ((want - model[v]) / 20)))))
        vel_rows.append(row)
    # GM2 / XG: L = 40 log10(c / 127) dB, the curve Yamaha's tone generators
    # use for CC7 volume and CC11 expression (100, the reset value, is -4.2 dB)
    law40 = [0] + [int(round(32767 * (c / 127.0) ** 2)) for c in range(1, 128)]
    law30 = [int(round(32767 * 10 ** (-30.0 * (127 - c) / 127.0 / 20))) for c in range(128)]
    parts = [
        "/* Generated by tools/gen_cc_tables.py: do not edit by hand. */",
        f"/* velocity -> output share, Q12 (127 = 4064, as v/128 was), one row a\n"
        f" * family (strings, woodwinds, brass, mallets, choir): each family's\n"
        f" * models get louder with velocity by their own amount (brass hardly,\n"
        f" * mallets by 45 dB), so each has its share; the whole note lands on the\n"
        f" * same even line, {VEL_RANGE_DB:.0f} dB from 1 to 127, in every family */",
        "static const uint16_t VEL_OUT_Q12[5][128] = {",
        *["    {" + ", ".join(f"{x}U" for x in row) + "}," for row in vel_rows],
        "};",
        "/* CC7 volume and CC11 expression, Q15: the GM2/XG curve, 40 log10(c/127)\n * dB, as a Yamaha tone generator applies it; 0 is silent */",
        table("LAW_GM2_Q15", "uint16_t", law40),
        "/* CC1 / CC2 dynamics, Q15: even in dB over 30 dB, 0 is pianissimo, not off */",
        table("LAW30_Q15", "uint16_t", law30),
        "/* attack and decay, ms: 1 .. 4000 on a log scale */",
        table("ATTACK_MS", "uint16_t", log_law(1, 4000)),
        "/* release, ms: 1 .. 6000 on a log scale */",
        table("RELEASE_MS", "uint16_t", log_law(1, 6000)),
        "/* LFO rate, mHz: 0.1 .. 20 Hz on a log scale */",
        table("RATE_MHZ", "uint16_t", log_law(100, 20000)),
        "/* LFO delay, ms: 0, then 5 .. 5000 on a log scale */",
        table("DELAY_MS", "uint16_t", log_law(5, 5000, zero=0)),
        "/* velocity steps per dB on the even line: 126 steps over VEL_RANGE_DB */",
        f"#define VEL_STEPS_PER_DB_Q8 {int(round(256 * 126 / VEL_RANGE_DB))}",
        "/* what CC11 expression takes off the played dynamic, in velocity steps",
        " * (the GM2 curve on the even line): the adaptive layer, ARP and SEQ hear a",
        " * line played under expression 64 as about 47 steps softer */",
        "static const int8_t EXPR_STEPS[128] = {",
        "    " + ", ".join(str(-127 if c == 0 else max(-127, int(round(40 * math.log10(c / 127) * 126 / VEL_RANGE_DB)))) for c in range(128)) + ",",
        "};",
        "/* the same for CC2 breath (even, 30 dB) */",
        "static const int8_t BREATH_STEPS[128] = {",
        "    " + ", ".join(str(int(round(-30.0 * (127 - c) / 127 * 126 / VEL_RANGE_DB))) for c in range(128)) + ",",
        "};",
        "/* 2^(k/64) in Q16, k = 0..64: pitch bend without a pow() */",
        "static const uint32_t EXP2_Q16[65] = {",
        "    " + ", ".join(f"{int(round(65536 * 2 ** (k / 64)))}U" for k in range(65)) + ",",
        "};",
        "",
    ]
    (ROOT / "app" / "orch_cc_tables.inc").write_text("\n".join(parts))

main()
